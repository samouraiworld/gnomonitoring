#!/usr/bin/env python3
"""Create a private backup-format bundle from invented PostgreSQL fixture rows.

No Docker command runs without --execute-synthetic. The source is always a new
network:none container with no host data mounts and no existing volume.
"""

import argparse
import contextlib
import importlib.util
import io
import json
import os
from pathlib import Path
import platform
import secrets
import stat
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
PG_IMAGE = "postgres:16@sha256:9e2cf6287f25c3151f4c9421ccce2b17f3e60061c111a29165e0d2cdd9ff0a97"
SPEC = importlib.util.spec_from_file_location("synthetic_backup_tool", ROOT / "scripts/backup/prepare-postgres-backup.py")
BACKUP = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(BACKUP)
SNAPSHOT_SPEC = importlib.util.spec_from_file_location("synthetic_source_snapshot", HERE / "synthetic_snapshot.py")
SNAPSHOT = importlib.util.module_from_spec(SNAPSHOT_SPEC)
SNAPSHOT_SPEC.loader.exec_module(SNAPSHOT)


class SyntheticError(Exception):
    pass


def approved_socket(requested=None):
    if platform.system() == "Darwin":
        expected = Path.home() / ".docker/run/docker.sock"
    elif platform.system() == "Linux":
        expected = Path("/var/run/docker.sock")
    else:
        raise SyntheticError("local_linux_docker_required")
    if requested is not None and Path(requested) != expected:
        raise SyntheticError("approved_local_socket_required")
    return BACKUP.validate_docker_socket(str(expected))


def private_empty_directory(value):
    path = Path(value)
    if not path.is_absolute() or path.resolve(strict=True) != path:
        raise SyntheticError("canonical_private_fixture_directory_required")
    info = path.stat()
    if not stat.S_ISDIR(info.st_mode) or info.st_uid != os.geteuid() or stat.S_IMODE(info.st_mode) != 0o700 or any(path.iterdir()):
        raise SyntheticError("empty_owned_0700_fixture_directory_required")
    # Reuse the real exporter's ancestor/ownership/outside-Git policy.
    BACKUP.validate_destination(str(path))
    return path


def create_bundle(output, docker_socket=None, variant="valid", *, capture_source=False):
    """Return a bundle generated by the real backup helper, never production."""
    if variant not in {"valid", "reserved-marker", "restore-error", "restore-timeout"}:
        raise SyntheticError("unknown_synthetic_variant")
    output = private_empty_directory(output)
    socket = approved_socket(docker_socket)
    configuration = output / "docker-config"
    configuration.mkdir(mode=0o700)
    (configuration / "config.json").write_text('{"auths":{},"currentContext":"default"}\n')
    (configuration / "config.json").chmod(0o600)
    docker = ["docker", "--config", str(configuration), "--host", "unix://" + socket]
    source_name = "gnomon-restore-fixture-" + secrets.token_hex(12)
    project = source_name
    private = BACKUP.Runner(output)
    container = None
    bundle = None
    original = None
    os.umask(0o077)
    try:
        inspected = json.loads(private.run(docker + ["info", "--format", '{"os":{{json .OSType}}}']))
        if inspected != {"os": "linux"}:
            raise SyntheticError("local_linux_docker_required")
        container = private.run(docker + [
            "create", "--name", source_name, "--label", "com.docker.compose.project=" + project,
            "--network", "none", "--user", "999:999", "--cap-drop", "ALL", "--security-opt", "no-new-privileges:true",
            "--pids-limit", "128", "--memory", "1g", "--cpus", "2",
            "--tmpfs", "/var/lib/postgresql/data:uid=999,gid=999,mode=0700",
            "--tmpfs", "/var/run/postgresql:uid=999,gid=999,mode=0777",
            "--env", "POSTGRES_USER=fixture_admin", "--env", "POSTGRES_DB=fixture_archive",
            "--env", "POSTGRES_PASSWORD=" + secrets.token_hex(24),
            PG_IMAGE, "postgres", "-c", "listen_addresses=", "-c", "unix_socket_directories=/var/run/postgresql",
        ], timeout=90).decode().strip()
        if not BACKUP.CONTAINER.fullmatch(container):
            raise SyntheticError("unexpected_fixture_container_id")
        template = '{"network":{{json .HostConfig.NetworkMode}},"ports":{{json .HostConfig.PortBindings}},"mounts":{{json .Mounts}},"user":{{json .Config.User}},"caps":{{json .HostConfig.CapDrop}},"security":{{json .HostConfig.SecurityOpt}}}'
        runtime = json.loads(private.run(docker + ["inspect", "--format", template, container]))
        if (runtime.get("network") != "none" or runtime.get("ports") or runtime.get("user") != "999:999"
                or runtime.get("caps") != ["ALL"] or "no-new-privileges:true" not in runtime.get("security", [])
                or any(m.get("Type") != "tmpfs" for m in runtime.get("mounts", []))):
            raise SyntheticError("source_fixture_fence_mismatch")
        private.run(docker + ["start", container], timeout=15)
        deadline = time.monotonic() + 60
        while True:
            try:
                private.run(docker + ["exec", container, "sh", "-c", 'test "$(head -n 1 "$PGDATA/postmaster.pid")" = 1'], timeout=5)
                private.run(docker + ["exec", container, "psql", "-X", "-w", "-h", "/var/run/postgresql", "-U", "fixture_admin", "-d", "fixture_archive", "-Atc", "SELECT 1"], timeout=5)
                break
            except BACKUP.BackupError:
                if time.monotonic() >= deadline:
                    raise SyntheticError("synthetic_source_startup_timeout") from None
                time.sleep(0.2)
        fixtures = [HERE / "fixtures/archive.sql"]
        if variant != "valid":
            fixtures.append(HERE / f"fixtures/{variant}.sql")
        for fixture in fixtures:
            with fixture.open("rb") as sql:
                private.run(docker + ["exec", "-i", container, "psql", "-X", "-w", "-v", "ON_ERROR_STOP=1", "-h", "/var/run/postgresql", "-U", "fixture_admin", "-d", "fixture_archive"], input_file=sql, reject_stderr=True)
        snapshot = None
        source_version = None
        if capture_source:
            # This private source has no published socket/port, no application,
            # and no other writer. Freeze new connections before snapshot/dump.
            def sql(query):
                return private.run(docker + ["exec", container, "psql", "-X", "-q", "-t", "-A", "-w",
                    "-v", "ON_ERROR_STOP=1", "-h", "/var/run/postgresql", "-U", "fixture_admin",
                    "-d", "fixture_archive", "-c", query], reject_stderr=True).decode("utf-8")
            sql("ALTER DATABASE fixture_archive SET default_transaction_read_only=on")
            if sql("SHOW transaction_read_only").strip() != "on":
                raise SyntheticError("synthetic_source_freeze_failed")
            source_version = sql("SHOW server_version").strip()
            snapshot = SNAPSHOT.capture_snapshot(sql)
        image = private.run(docker + ["inspect", "--format", "{{.Image}}", container]).decode().strip()
        destination = output / "bundles"
        destination.mkdir(mode=0o700)
        # The real tool produces and checks the archive, globals, TOC and
        # manifest; no fixture-only copy of that export implementation exists.
        args = ["--docker-socket", socket, "--container-id", container,
                "--expected-image-id", image, "--compose-project", project,
                "--database", "fixture_archive", "--user", "fixture_admin", "--postgres-major", "16",
                "--socket-directory", "/var/run/postgresql", "--port", "5432",
                "--destination", str(destination), "--dump-timeout-seconds", "60", "--execute"]
        captured = io.StringIO()
        with contextlib.redirect_stdout(captured), contextlib.redirect_stderr(captured):
            status = BACKUP.main(args)
        if status != 0:
            raise SyntheticError("synthetic_backup_generation_failed")
        bundles = list(destination.iterdir())
        if len(bundles) != 1:
            raise SyntheticError("synthetic_bundle_not_unique")
        bundle = bundles[0]
        manifest = json.loads((bundle / "manifest.json").read_text())
        if manifest.get("complete") is not True or manifest.get("restore_verified") is not False or not manifest.get("source", {}).get("compose_project", "").startswith("gnomon-restore-fixture-"):
            raise SyntheticError("synthetic_export_manifest_invalid")
        if capture_source:
            SNAPSHOT.write_source_receipt(bundle, snapshot, source_version, [fixture.name for fixture in fixtures])
    except BaseException as error:
        original = error
        raise
    finally:
        if container:
            try:
                private.run(docker + ["rm", "--force", container], timeout=30)
                remaining = private.run(docker + ["ps", "--all", "--quiet", "--filter", "name=^/" + source_name + "$"])
                if remaining:
                    raise SyntheticError("synthetic_source_cleanup_incomplete")
            except BaseException:
                if original is None:
                    raise
    return bundle


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--execute-synthetic", action="store_true")
    parser.add_argument("--private-output-dir")
    parser.add_argument("--docker-socket")
    parser.add_argument("--capture-source", action="store_true", help="write a separate private receipt for the frozen invented source")
    parser.add_argument("--variant", choices=["valid", "reserved-marker", "restore-error", "restore-timeout"], default="valid")
    args = parser.parse_args(argv)
    if not args.execute_synthetic:
        print(json.dumps({"status": "tools_only", "synthetic_only": True, "action": "none"}))
        return 0
    if not args.private_output_dir:
        parser.error("--private-output-dir is required with --execute-synthetic")
    try:
        bundle = create_bundle(args.private_output_dir, args.docker_socket, args.variant, capture_source=args.capture_source)
    except (SyntheticError, SNAPSHOT.SnapshotError, BACKUP.BackupError, OSError, ValueError, subprocess.SubprocessError):
        print(json.dumps({"status": "synthetic_bundle_failed", "synthetic_only": True}), file=sys.stderr)
        return 1
    print(json.dumps({"status": "synthetic_bundle_created", "synthetic_only": True,
                      "bundle": str(bundle), "source_cleanup_verified": True, "production_data_used": False}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
